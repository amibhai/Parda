import java.util.Properties
import java.io.FileInputStream
// Imported rather than written as `java.io.StringReader` inline: inside
// the Gradle Kotlin DSL, `java` resolves to the JavaPluginExtension
// accessor on Project, so the fully-qualified form fails to compile.
import java.io.StringReader

plugins {
    id("com.android.application")
    // The Flutter Gradle Plugin must be applied after the Android and Kotlin Gradle plugins.
    id("dev.flutter.flutter-gradle-plugin")
}

// Release signing.
//
// Credentials live in `android/key.properties`, which is gitignored — a
// keystore or its passwords in version control would let anyone publish
// an update that Android accepts as this app. When the file is absent
// (every fresh clone, and CI) the release build falls back to the debug
// key and says so, rather than failing: an unsigned-for-distribution
// build is still useful for testing, and a silent fallback would be
// worse than a loud one.
//
// To produce a real release build:
//   keytool -genkey -v -keystore parda-release.jks -keyalg RSA -keysize 4096 -validity 10000 -alias parda
//   cat > android/key.properties <<EOF
//   storeFile=/absolute/path/to/parda-release.jks
//   storePassword=...
//   keyAlias=parda
//   keyPassword=...
//   EOF
val keystoreProperties = Properties().apply {
    val f = rootProject.file("key.properties")
    if (f.exists()) load(FileInputStream(f))
}
val hasReleaseKeystore = keystoreProperties.getProperty("storeFile") != null

// ── Relay TLS: certificate pinning ───────────────────────────────────
//
// Android blocks cleartext HTTP to anything but loopback by default, so
// a relay on a real host must speak TLS. This app does not rely on the
// public CA system to authenticate it. It pins a single certificate
// authority generated by `parda-cli gen-certs`, which is stronger than
// the default path (one trusted key instead of the ~150 roots Android
// ships, any of which can issue for any name) and keeps the relay's
// hostname out of Certificate Transparency logs. The reasoning is in
// `tls/src/lib.rs`'s `pinned_authority`, and the property is proved by
// `tls/tests/tls_integration_tests.rs` test 7, which serves a valid
// certificate from a *different* authority and asserts it is refused.
//
// Both inputs are deployment-specific and gitignored:
//   android/relay.properties            relayHost=<host or IP>
//   app/src/main/res/raw/parda_relay_ca.pem   the authority certificate
//
// When either is missing — a fresh clone, CI — the build still succeeds
// and produces an app that trusts the system CAs instead, with a loud
// warning. It fails *open* on trust here, deliberately and narrowly:
// making a missing local file break the build would mean nobody could
// compile this project without first standing up a relay. Cleartext
// stays blocked either way, so the unconfigured build is still HTTPS-only
// — it just authenticates the way an ordinary app does.
val relayProperties = Properties().apply {
    val f = rootProject.file("relay.properties")
    if (f.exists()) {
        // Read as UTF-8 with any byte-order mark stripped, rather than
        // handing the stream straight to `Properties.load`.
        //
        // `Properties.load(InputStream)` decodes ISO-8859-1, so a file
        // written by PowerShell's `Set-Content -Encoding utf8` or by
        // Notepad — both of which emit a BOM — turns `relayHost` into
        // `﻿relayHost`. The lookup then returns null, pinning
        // silently switches itself off, and the build still succeeds.
        // That cost a real debugging cycle here, on the exact platform
        // this project is developed on; it is not left as a trap.
        load(StringReader(f.readText(Charsets.UTF_8).removePrefix("﻿")))
    }
}
val relayHost: String? = relayProperties.getProperty("relayHost")?.trim()?.ifEmpty { null }
val relayCaFile = file("src/main/res/raw/parda_relay_ca.pem")
val pinningActive = relayHost != null && relayCaFile.exists()

// Half-configured fails the build, rather than quietly producing an
// unpinned APK.
//
// This mirrors `TlsSettings::from_env`'s handling of a cert path without
// its key (`tls/src/lib.rs`), and for the same reason: someone who has
// placed one of the two files has declared their intent, and the
// dangerous outcome is not a failed build but a *successful* one that
// ships an app trusting the public CA store while a certificate sits in
// `res/raw` making it look pinned. Only the both-absent case — a fresh
// clone, CI — is allowed through with a warning.
if (relayHost != null && !relayCaFile.exists()) {
    throw GradleException(
        "PARDA: android/relay.properties sets relayHost=$relayHost but " +
            "${relayCaFile.path} does not exist. Refusing to build an APK that would silently " +
            "trust the public CA store for that host. Generate the authority with " +
            "`cargo run -p parda-cli -- gen-certs --san $relayHost` and copy authority-cert.pem " +
            "to that path, or remove relay.properties to build unpinned on purpose."
    )
}
if (relayHost == null && relayCaFile.exists()) {
    throw GradleException(
        "PARDA: ${relayCaFile.path} exists but android/relay.properties does not set relayHost. " +
            "A pinned certificate with no host to pin it to has no effect, and shipping this " +
            "build would look configured while trusting the public CA store. Set relayHost, or " +
            "delete the certificate to build unpinned on purpose."
    )
}
if (!pinningActive) {
    logger.warn(
        "PARDA: relay certificate pinning is OFF — this build trusts the system CA store for the " +
            "relay connection. Cleartext HTTP is still blocked. Before distributing an APK, run " +
            "`cargo run -p parda-cli -- gen-certs --san <host>`, copy authority-cert.pem to " +
            "${relayCaFile.path}, and set relayHost in android/relay.properties."
    )
}

// Generated rather than committed: the pinned host is deployment
// -specific, and a checked-in config would either hardcode someone
// else's relay or carry a placeholder that silently does nothing.
val pardaGeneratedRes = layout.buildDirectory.dir("generated/parda/res").get().asFile
File(pardaGeneratedRes, "xml").mkdirs()
File(pardaGeneratedRes, "xml/network_security_config.xml").writeText(
    buildString {
        appendLine("<?xml version=\"1.0\" encoding=\"utf-8\"?>")
        appendLine("<!-- Generated by app/build.gradle.kts. Do not edit. -->")
        appendLine("<network-security-config>")
        appendLine("    <base-config cleartextTrafficPermitted=\"false\">")
        appendLine("        <trust-anchors><certificates src=\"system\"/></trust-anchors>")
        appendLine("    </base-config>")
        if (pinningActive) {
            appendLine("    <domain-config cleartextTrafficPermitted=\"false\">")
            appendLine("        <domain includeSubdomains=\"true\">$relayHost</domain>")
            appendLine("        <trust-anchors>")
            // Note the absence of src="system": replacing the anchor set
            // rather than adding to it is what makes this a pin. With the
            // system store still listed, any public CA could still issue
            // for this host and the whole exercise would be decorative.
            appendLine("            <certificates src=\"@raw/parda_relay_ca\"/>")
            appendLine("        </trust-anchors>")
            appendLine("    </domain-config>")
        }
        // Loopback stays cleartext-permitted in every build type, so
        // `adb reverse tcp:8080 tcp:8080` against a local relay keeps
        // working. Scoped to addresses that cannot leave the handset: an
        // attacker cannot position themselves on a device's own loopback
        // interface, so this is not a downgrade of anything reachable.
        appendLine("    <domain-config cleartextTrafficPermitted=\"true\">")
        appendLine("        <domain includeSubdomains=\"false\">127.0.0.1</domain>")
        appendLine("        <domain includeSubdomains=\"false\">10.0.2.2</domain>")
        appendLine("        <domain includeSubdomains=\"false\">localhost</domain>")
        appendLine("    </domain-config>")
        appendLine("</network-security-config>")
    }
)

android {
    namespace = "com.parda.app"
    compileSdk = flutter.compileSdkVersion
    ndkVersion = flutter.ndkVersion

    sourceSets {
        getByName("main") {
            res.srcDir(pardaGeneratedRes)
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
        // libsignal-android's AAR metadata requires this (found via a
        // real build failure — `checkDebugAarMetadata`, not assumed).
        isCoreLibraryDesugaringEnabled = true
    }

    defaultConfig {
        applicationId = "com.parda.app"
        // Sub-Phase 4.5B: BluetoothLeAdvertiser (peripheral/advertise role,
        // MeshPlugin.kt) is unreliable before API 26 (Oreo) per Android's
        // own documentation — the default `flutter.minSdkVersion` (21) is
        // too low for the mesh radio backend this phase adds, so it's
        // raised explicitly rather than discovered as a runtime failure
        // on older devices.
        minSdk = maxOf(flutter.minSdkVersion, 26)
        targetSdk = flutter.targetSdkVersion
        versionCode = flutter.versionCode
        versionName = flutter.versionName
        // Sub-Phase 4.5C: required for PlaintextForensicRecoveryTest.kt
        // (androidTest) to run at all.
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (hasReleaseKeystore) {
            create("release") {
                storeFile = file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            signingConfig = if (hasReleaseKeystore) {
                signingConfigs.getByName("release")
            } else {
                logger.warn(
                    "PARDA: android/key.properties not found — signing the release build with " +
                        "the DEBUG key. Fine for testing; never distribute this artifact."
                )
                signingConfigs.getByName("debug")
            }

            // Code shrinking is deliberately off.
            //
            // R8 strips classes it cannot see referenced, and most of
            // this app's Kotlin surface is reached only through JNI
            // (`MeshBridge`, `PlaintextBridge`) or reflection inside
            // libsignal. Getting the keep rules wrong produces a build
            // that installs and then fails at runtime in ways no test
            // here would catch. Turning it on needs a device pass that
            // has not been done, so it stays off rather than shipping an
            // untested optimisation.
            isMinifyEnabled = false
            isShrinkResources = false
        }
    }
}

